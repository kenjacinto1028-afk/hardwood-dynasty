// Fantasy league check (Nov 20 2026): setup, draft, matchup, standings, waivers, champion popup; 1300 + 390 px.
// Save: node -e (see PROGRESS.md) writes tools/_fan0.json (day 0); then: node tools/browser-fantasy.js
const { chromium } = require('playwright'); const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..'), BASE = 'http://pbl.test/';
const MIME = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.svg': 'image/svg+xml', '.png': 'image/png' };
let fails = 0; const ok = (n, c, x) => { console.log((c ? 'PASS ' : 'FAIL ') + n + (x !== undefined ? '  [' + JSON.stringify(x) + ']' : '')); if (!c) fails++; };
const wait = (pg, ms) => pg.waitForTimeout(ms);
const ev = (pg, js) => pg.evaluate(js0 => { const L = window.__pbl.L, ui = window.__pbl.ui; return eval(js0); }, js);
(async () => {
  const b = await chromium.launch({ args: ['--no-sandbox'] });
  for (const W of [1300, 390]) {
    const ctx = await b.newContext({ viewport: { width: W, height: 900 }, isMobile: W < 500, hasTouch: W < 500 });
    await ctx.route(BASE + '**', r => { const f = path.join(ROOT, decodeURIComponent(new URL(r.request().url()).pathname)); if (!f.startsWith(ROOT) || !fs.existsSync(f)) return r.fulfill({ status: 404, body: '' }); r.fulfill({ status: 200, body: fs.readFileSync(f), contentType: MIME[path.extname(f)] || 'application/octet-stream' }); });
    const pg = await ctx.newPage(), errs = []; pg.on('pageerror', e => errs.push(String(e)));
    await pg.goto(BASE + 'index.html'); await wait(pg, 1500);
    await pg.evaluate(async f => { const txt = await (await fetch(f)).text(); const db = await new Promise((res, rej) => { const r = indexedDB.open('pbl-league', 1); r.onupgradeneeded = () => r.result.createObjectStore('s'); r.onsuccess = () => res(r.result); r.onerror = () => rej(r.error); });
      const put = (k, v) => new Promise((res, rej) => { const tx = db.transaction('s', 'readwrite'); tx.objectStore('s').put(v, k); tx.oncomplete = res; tx.onerror = () => rej(tx.error); });
      await put('league:slot-c', txt); await put('slots', JSON.stringify([{ id: 'slot-c', name: 'c', mode: 'team', season: 11, phase: 'regular', updated: Date.now() }])); await put('current', 'slot-c'); }, '/tools/_fan0.json');
    await pg.reload(); await wait(pg, 5000);
    const close = () => pg.evaluate(() => { document.querySelector('#modal').innerHTML = ''; const m = document.getElementById('fx-modal'); if (m) m.innerHTML = ''; });
    await close();
    const shot = async n => { await pg.screenshot({ path: path.join(ROOT, 'tools', '_fan-' + n + '-' + W + '.png'), fullPage: false }); };
    const go = async () => { await pg.evaluate(() => { location.hash = '#fantasy'; }); await wait(pg, 800); };
    await go();
    ok(W + ': Fantasy tab in menu', await ev(pg, "!!document.querySelector('#subtabs a[data-v=fantasy]')"));
    ok(W + ': setup screen', await ev(pg, "!!document.querySelector('[data-fango]')"));
    await shot('setup');
    await pg.fill('#fan-name', 'Test Ballers'); await pg.click('[data-fango]'); await wait(pg, 1500);
    ok(W + ': draft room, your turn', await ev(pg, "!!L.fan && L.fan.draft.ord[L.fan.draft.i] === 0 && document.querySelectorAll('[data-fandraft]').length > 10"));
    await shot('draft');
    await pg.click('[data-fandraft]'); await wait(pg, 1500);
    ok(W + ': picked one', await ev(pg, "L.fan.teams[0].r.length === 1"));
    await pg.click('[data-fanauto=all]'); await wait(pg, 3000);
    ok(W + ': draft done', await ev(pg, "!!L.fan.draft.done && L.fan.teams.every(t => t.r.length === 10)"));
    await ev(pg, "(() => { for (let i = 0; i < 17; i++) simDay(L); window.__pbl.render(); return 1; })()"); await wait(pg, 1500);
    ok(W + ': weeks scored', await ev(pg, "L.fan.wk === 2 && L.fan.teams.reduce((a, t) => a + t.w, 0) === 8"), await ev(pg, "L.fan.wk"));
    ok(W + ': matchup score shows', await ev(pg, "!!document.querySelector('.fan-score') && document.querySelectorAll('.fan-mini tr').length >= 10"));
    ok(W + ': no horizontal page scroll (matchup)', await ev(pg, "document.documentElement.scrollWidth <= window.innerWidth + 1"), await ev(pg, "document.documentElement.scrollWidth"));
    await shot('matchup');
    await pg.click('[aria-label="Previous week"]'); await wait(pg, 500);
    ok(W + ': last week final', await ev(pg, "/You (won|lost)/.test(document.querySelector('.fan-score em').textContent)"));
    await pg.click('[data-fantab=standings]'); await wait(pg, 600);
    ok(W + ': standings 8 rows', await ev(pg, "document.querySelectorAll('table[data-sid=fanst] tbody tr').length === 8"));
    await shot('standings');
    await pg.click('[data-fantab=roster]'); await wait(pg, 600);
    await pg.click('[data-fandrop]'); await wait(pg, 500);
    await pg.click('[data-fanadd]:not([disabled])'); await wait(pg, 800);
    ok(W + ': waiver add', await ev(pg, "L.fan.moves.some(m => m.ti === 0) && /Added/.test(document.querySelector('.fan-msg').textContent)"));
    ok(W + ': no horizontal page scroll (roster)', await ev(pg, "document.documentElement.scrollWidth <= window.innerWidth + 1"));
    await shot('roster');
    await pg.click('[data-fantab=league]'); await wait(pg, 500);
    ok(W + ': all teams', await ev(pg, "document.querySelectorAll('.fan-teams .panel').length === 8"));
    await ev(pg, "(() => { let g = 0; while (L.phase === 'regular' && g++ < 200) simDay(L); window.__pbl.render(); return 1; })()"); await wait(pg, 2500);
    ok(W + ': champion + popup', await ev(pg, "L.fan.champ != null && (L.fanHist || []).length === 1 && !!document.querySelector('.fan-pop')"));
    await pg.screenshot({ path: path.join(ROOT, 'tools', '_fan-champ-' + W + '.png') });
    await close(); await pg.evaluate(() => { location.hash = '#fantasy'; window.__pbl.ui.fanTab = 'standings'; window.__pbl.render(); }); await wait(pg, 800);
    ok(W + ': bracket shows', await ev(pg, "!!document.querySelector('.fan-champ')"));
    await shot('bracket');
    ok(W + ': no page errors', errs.length === 0, errs.slice(0, 2));
    await ctx.close();
  }
  await b.close(); console.log(fails ? fails + ' FAIL' : 'ALL PASS');
})();
